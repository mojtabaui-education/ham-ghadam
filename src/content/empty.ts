/** وقتی قیدها هستند ولی کسی آزاد نیست. متنِ خودِ فریمِ فیگما. */
export function narrowResult(criteria: string[], blamed: string) {
  const quoted = criteria.map((label) => `«${label}»`)
  const joined =
    quoted.length <= 1
      ? (quoted[0] ?? '')
      : `${quoted.slice(0, -1).join('، ')} و ${quoted[quoted.length - 1]}`

  return {
    echo: `با ${joined} زمان آزادی پیدا نشد.`,
    cause: `بیشترِ محدودیت از «${blamed}» آمده است.`,
    actionLabel: `«${blamed}» را برداریم؟`,
  }
}

